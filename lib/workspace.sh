#!/usr/bin/env bash
# Где корни проекта — ОДНО место для лончеров и сторожей этого репозитория.
#
# **Зачем настройка, а не только путь от файла.** У проекта два корня: свой (`PROJECT_DIR` — здесь
# композ, `.env`, `wheels/`, `.sessions/`) и корень ВОРКСПЕЙСА (`WORKSPACE` — там общий `.env` и соседние
# продукты). Пока проект стоит внутри воркспейса, второй выводится из первого; в одиночном клоне
# воркспейса нет, и оба корня совпадают.
#
# Правило проекта: **путь к данным — настройкой, а не от расположения кода.** Каталог файлов-сессий
# Telegram, выведенный от `__file__`, после установки пакета указывал внутрь `site-packages`, и бот
# МОЛЧА не подключался при зелёных тестах. Поэтому порядок такой: сначала `AGENT_WORKSPACE` (её задают
# юниты через `Environment=`, то есть развёртывание), затем — вывод от файла.
#
# Подключение (путь считается от САМОГО вызывающего файла):
#   source "$PROJECT_DIR/lib/workspace.sh"
# После подключения доступны: `$PROJECT_DIR` (этот репозиторий), `$WORKSPACE` (корень воркспейса).

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKSPACE="${AGENT_WORKSPACE:-$(cd "$PROJECT_DIR/.." && pwd)}"

#: Проверка «воркспейс — это правда воркспейс»: без неё ошибка в `AGENT_WORKSPACE` дала бы сторожу
#: пустой `.env` и службу «не найдено» вместо внятного отказа (класс «зелёный при мёртвом»).
if [[ "$WORKSPACE" != "$PROJECT_DIR" && ! -f "$WORKSPACE/.env" ]]; then
  echo "[news] ОСТАНОВ: воркспейс не найден — нет $WORKSPACE/.env." >&2
  echo "       Задайте AGENT_WORKSPACE (юниты задают её через Environment=) или запускайтесь из проекта." >&2
  return 1 2>/dev/null || exit 1
fi
