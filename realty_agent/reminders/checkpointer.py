"""Чекпойнтер графа: состояние процесса живёт в PostgreSQL.

**Почему в базе векторного контейнера, а не в `bridge`.** Платформенный `postgres:17`
специально не трогаем (там база `bridge` — наша схема со своим гейтом), а рядом уже
работает база векторов. Новая база внутри того же контейнера — это ещё один объект
эксплуатации; корпус и чекпойнты в одной базе разведены по назначению, а не по
контейнеру, и это названо, а не умолчано.

**Своих таблиц граф не заводит.** Их создаёт `AsyncPostgresSaver.setup()` — три таблицы
библиотеки. В `realty_agent/db/repo.py` их нет намеренно: гейт схемы считает **наши** объекты, и
добавлять туда чужие значило бы смешать «схема приложения» и «внутренности библиотеки».

**Один пул на процесс.** Мост живёт неделями (`Restart=always`), поэтому соединение
берём из пула: одиночное соединение при обрыве уронило бы весь поток напоминаний.
"""
from __future__ import annotations

import logging
from contextlib import asynccontextmanager

log = logging.getLogger(__name__)


def checkpoint_dsn(configured: str) -> str:
    """DSN чекпойнт-базы: ТОЛЬКО явный, без вывода из адреса векторов.

    **Почему запрет, а не «удобное значение по умолчанию».** Пустой `REMINDERS_CHECKPOINT_DSN` не
    подменяется адресом базы векторов: иначе состояние графа складывается в ту же базу, что корпус
    RAG, и «отдельное хранилище» существует только на бумаге — подмена ТИХАЯ, процесс поднимается и
    работает. Пустая настройка — отказ с названной причиной: пусть напоминания не поднимутся и скажут
    об этом вслух.

    Драйвер приводим к `postgresql://`: saver работает через `psycopg`, а остальные DSN проекта
    записаны с драйвером SQLAlchemy (`+asyncpg`) — это единственное место, где встречаются оба.
    """
    text = (configured or "").strip()
    if not text:
        raise ValueError(
            "REMINDERS_CHECKPOINT_DSN не задан: чекпойнт-база графа задаётся ЯВНО — "
            "молчаливая подстановка базы векторов запрещена (состояние графа и корпус RAG "
            "имеют разные жизненные циклы)")
    return text.replace("+asyncpg", "").replace("postgresql+psycopg", "postgresql")


@asynccontextmanager
async def open_checkpointer(dsn: str):
    """Открыть saver поверх пула и создать таблицы чекпойнтов (идемпотентно).

    `autocommit=True` и `prepare_threshold=0` — требования saver'а: он выполняет
    собственные транзакции, а подготовленные выражения мешают его запросам при
    переключении соединений в пуле.

    Импорты LangGraph — **внутри функции**, и это не небрежность: правило проекта
    «необязательная зависимость деградирует, а не валит основной путь» (так же сделана
    база знаний). Если пакета нет или чекпойнт-база недоступна, мост обязан
    подняться без напоминаний, а не упасть целиком.
    """
    from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
    from psycopg_pool import AsyncConnectionPool

    pool = AsyncConnectionPool(
        dsn,
        min_size=1,
        max_size=4,
        open=False,
        kwargs={"autocommit": True, "prepare_threshold": 0},
    )
    await pool.open(wait=True, timeout=30)
    try:
        saver = AsyncPostgresSaver(pool)
        await saver.setup()
        log.info("граф: чекпойнтер готов (таблицы чекпойнтов созданы или уже были)")
        yield saver
    finally:
        await pool.close()
