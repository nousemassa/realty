"""Лексика, общая для СХЕМЫ и предметного кода (`0024`, срез 3).

**Почему эти два имени живут в общем слое, а не рядом с теми, кто их придумал.** `db/pg.py` — общий
слой: базу используют и продукт, и новости. Ему были нужны две вещи, лежавшие в продуктовых модулях:

* `VISIT_RESULTS` — допустимые значения колонки `bookings.visit_result`. Это **часть схемы**, а не мнение
  продукта: колонка объявлена в общем слое, и список её значений обязан быть там же — иначе схема и её
  лексика разъедутся, и разъедутся молча (строка с недопустимым значением просто не запишется).
* `CalendarEvent` — форма строки таблицы календаря. Её читает **только** база (`db/pg.py`), то есть это уже
  контракт базы, а не коннектора; коннектор её производит.

**Оба имени остаются доступны по прежним адресам** — `booking/visits.py` и `connectors/calendar.py`
реэкспортируют их, поэтому код, знающий их оттуда, менять не нужно. Источник истины при этом один.

**Чего здесь быть не должно.** Слов и фраз предметной области (тексты напоминаний, разбор ответов клиента):
они правятся по продуктовым причинам и остаются у продукта — иначе общий слой превратится в свалку.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime

#: Что допустимо записать в `bookings.visit_result`. Состояний в колонке три (NULL — ещё не отмечено),
#: а отметок две: «пришёл» и «не пришёл».
VISIT_RESULTS = ("attended", "no_show")


@dataclass(frozen=True)
class CalendarEvent:
    """Событие календаря в том виде, в каком его записывает и читает база.

    `starts_at` — осведомлённое время в UTC (приведение делает коннектор): база не должна знать ни про
    часовые пояса, ни про правила повторения — это забота того, кто разбирает iCal.

    `all_day` по умолчанию `False`: событие «на весь день» отличается от встречи в полночь, и это
    различие приходит из внешнего календаря, а не выводится из времени.
    """

    uid: str
    summary: str
    location: str
    starts_at: datetime  # aware, UTC
    all_day: bool = False
