"""ACL: роль заявителя берётся из БД, ответ ограничивается набором полей.

Зачем это здесь, а не «в middleware». В проекте уже есть ключ (`X-API-Key`) и таблица
`managers` с ролями, но роль нигде не использовалась: ключ один на всё, и запрос не
отличал владельца от клиента.a добавляет ровно две вещи и не больше:

1. **идентичность сопоставляется со строкой в `managers`**, а роль и признак `active`
   читаются **из БД**. Заголовок с ролью ничего не меняет — иначе разграничение было бы
   декоративным;
2. **ответ ограничивается полями, а не отклоняется.** Клиентский контекст получает
   публичные поля объекта; внутренние (идентификатор сессии агента, описание фото,
   стоимость, латентность) достаются только владельцу. Отказ 403 здесь сломал бы
   сценарий генерации объявлений, поэтому решение владельца — именно ограничение.

Чего здесь НЕТ и почему: выпуска токенов, таблиц аккаунтов и внешнего провайдера
идентичности. Этоb, и он отложен. Поэтому заявление «агент действует от имени
пользователя» остаётся **частичным**: роль проверяется, но у вызывающей стороны нет
своего креденшела — ключ остаётся общим машинным.

**Граница этого ACL — называть её прямо.** Он разграничивает **роли среди тех, кто
заявил идентичность**, и снимает риск случайной утечки внутренних полей в клиентский
контекст. Он НЕ является защитой от держателя ключа: заявив себя владельцем по чужому
`chat_id` (или не заявив идентичность вовсе), тот же ключ даёт полный набор. Полноценной
границей это станет только вместе со своим креденшелом на пользователя — то есть вb.
"""
from __future__ import annotations

from dataclasses import dataclass

# Поля ответа генерации объявления: что можно отдать клиентскому контексту, а что нет.
PUBLIC_RESPONSE_FIELDS = ("job_id", "listing_short", "listing_long")
INTERNAL_RESPONSE_FIELDS = ("session_id", "photo_description", "duration_ms", "cost_usd")

DEFAULT_PLATFORM = "tg"
ROLE_OWNER = "owner"


@dataclass(frozen=True)
class Identity:
    """Заявитель запроса, подтверждённый строкой в `managers`."""

    platform: str
    chat_id: str
    role: str

    @property
    def is_owner(self) -> bool:
        return self.role == ROLE_OWNER


async def resolve_identity(db, *, platform: str, chat_id: str) -> Identity | None:
    """Найти активную строку в `managers`. Неизвестный или неактивный — `None`.

    Роль возвращает БД (`role` в `managers`: `owner|manager`), а не вызывающая сторона.
    """
    if not chat_id:
        return None
    role = await db.manager_role(platform=platform, chat_id=chat_id)
    if not role:
        return None
    return Identity(platform=platform, chat_id=chat_id, role=role)


def restrict_response(payload: dict, identity: Identity | None) -> dict:
    """Ограничить ответ по роли.

    Владелец и **отсутствие заявленной идентичности** видят полный набор — второе
    сохраняет поведение прежним (сервис зовёт сам себя: сторож, скрипты владельца).
    Остальные — только публичные поля: ключи внутренних полей **не появляются в ответе
    вообще** (а не приходят пустыми), чтобы клиентский контекст не мог отличить «поля
    нет» от «поля нет, потому что оно скрыто».
    """
    if identity is None or identity.is_owner:
        return dict(payload)
    return {key: payload[key] for key in PUBLIC_RESPONSE_FIELDS if key in payload}
