"""Признак явки и ответ клиента на напоминание о визите. Только чистые функции.

Здесь нет ни графа, ни базы, ни сети: словарь предметной области и решения, которые
можно проверить без LangGraph и без PostgreSQL. Граф напоминаний (`realty_agent/reminders/`) их
использует, база (`realty_agent/db/repo.py`) — тоже (`VISIT_RESULTS`), поэтому модуль лежит ниже обоих.

**Зачем отдельный модуль, а не константы в графе.** Список фраз и правило деления на
группы — это то, что будет правиться по продуктовым причинам, а не по техническим.
Держать их рядом с чекпойнтами значило бы менять граф ради формулировки.
"""
from __future__ import annotations

import re
import zlib
from datetime import date

from realty_agent import vocab

#: Допустимые значения колонки — ЧАСТЬ СХЕМЫ, поэтому живут в общем слое (`agent_core/vocab.py`):
#: колонка объявлена там же, и её лексика обязана быть рядом с ней. Здесь — РЕЭКСПОРТ: адрес
#: `realty_agent.booking.visits.VISIT_RESULTS` продолжает работать, но источник истины один.
VISIT_RESULTS = vocab.VISIT_RESULTS

# Текст напоминания — ШАБЛОН, ровно как существующее `OFFER_REMINDER_TEXT`
# (`realty_agent/dialog.py:868` возвращает константу в `Reply`, а не ответ модели).
# Пункт не про генерацию текста: менеджер всё равно правит его перед отправкой (узел
# `revise`), а вызов модели на каждом напоминании стоил бы денег и тянул бы платформу
# в путь, где она не нужна.
VISIT_REMINDER_TEXT = (
    "Напоминаем о просмотре: {slot}, объект {address}.\n"
    "Если планы изменились — ответьте «перенести» или нажмите кнопку."
)

# Короткие ответы, которые граф забирает себе вместо диалогового агента. Основной путь
# ответа — кнопки; этот список второй, и он ЗАКРЫТЫЙ. Расширять его — продуктовое
# решение, а не деталь кода: разбор произвольных формулировок превратился бы во второй
# FSM рядом с FSM диалога.
VISIT_ANSWER_YES = frozenset({"да", "приду", "буду", "ок", "окей", "хорошо", "подтверждаю"})
VISIT_ANSWER_MOVE = frozenset({
    "не смогу", "перенесите", "перенести", "перенесем", "не получится",
    "давайте перенесем", "другое время",
})

_PUNCTUATION = re.compile(r"[.!?,;:]+$")


def normalize_answer(text: str) -> str:
    """Привести ответ к виду, по которому идёт сравнение: регистр, `ё`, пробелы, знаки.

    Нормализация нарочно скромная: она не «понимает» текст, а только убирает различия,
    из-за которых точное совпадение не сработало бы («Да!», «да  », «перенесём»).
    """
    lowered = (text or "").strip().lower().replace("ё", "е")
    collapsed = " ".join(lowered.split())
    return _PUNCTUATION.sub("", collapsed).strip()


def classify_answer(text: str) -> str | None:
    """`yes` | `move` | `None`. Точное совпадение по закрытому списку фраз.

    `None` означает «граф это не берёт» — сообщение уходит агенту обычным ходом, как
    сегодня. Молчаливый ответ (клиент ничего не написал) — это тоже `None`, но решение
    о повторе принимает таймаут графа, а не эта функция.
    """
    normalized = normalize_answer(text)
    if normalized in VISIT_ANSWER_YES:
        return "yes"
    if normalized in VISIT_ANSWER_MOVE:
        return "move"
    return None


def reminder_group(*, manager_chat_id: str, slot_date: date, share: int) -> str:
    """Группа замера: `treatment` (напоминание уходит) или `control` (не уходит).

    **Делим по менеджеру и дате слота, а не по клиенту** — так требует спецификация
    пункта. Причина в смысле замера: отбор по клиенту собрал бы в контрольную группу
    постоянных клиентов, и «доля пришедших» мерила бы их привычки, а не эффект
    напоминания.

    Функция чистая и детерминированная, поэтому группу можно пересчитать в любой момент
    и не хранить в базе. Это и делает сплит проверяемым: правило видно в коде, а не в
    истории изменений строк.
    """
    digest = zlib.crc32(f"{manager_chat_id}|{slot_date.isoformat()}".encode())
    return "treatment" if digest % 100 < max(0, min(100, share)) else "control"


def is_treatment(*, manager_chat_id: str | None, slot_date: date, share: int) -> bool:
    """Попадает ли визит в группу с напоминанием. Без менеджера — всегда контрольная.

    Почему так: у брони без подтвердившего менеджера нет половины ключа деления, и
    отнести её к «с напоминанием» значило бы приписать напоминанию чужие визиты.
    """
    if not manager_chat_id:
        return False
    return reminder_group(manager_chat_id=manager_chat_id, slot_date=slot_date, share=share) == "treatment"
