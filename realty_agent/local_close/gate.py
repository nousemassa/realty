"""Гейт диалога «это ТОЛЬКО условие выбора объекта?».

**Зачем он нужен.** Полосу локального закрытия открывает гейт. Регулярка «после выкидывания служебных
слов остаётся не больше одного значимого токена» клиентов не описывает: на хранимой истории (81 ход)
в полосу не попадает **ни один ход** — определение пусто по построению. Поэтому тот же вопрос
задаётся **локальному решателю** `solver` словами: «сообщение — только условие, без вопроса и без
выбора?».

**Что гейт НЕ делает.** Он не строит спецификацию. Спецификацию по-прежнему собирает наш код
(`realty_agent/booking/filter.py::parse_constraints`): решатель отвечает на один вопрос с вариантами, а не
порождает структуру. Поэтому гейт не может «выдумать» фильтр — он может только разрешить применить
уже разобранный.

**Почему вопрос и варианты живут здесь одни на двух потребителей** — на живой путь и на замер:
разойдись они, замер мерил бы не тот вопрос, который задаётся в работе.

**Деградация — в сторону агента.** Решателя нет или ответ не разобран ⇒ гейт закрыт (идём к агенту).
«Не знаю» — не «да»: молча применить локальный фильтр там, где мы не
уверены, значило бы менять выдачу клиенту на догадке.
"""
from __future__ import annotations

from collections.abc import Awaitable, Callable

from agent_core.decisions.client import Decision, SolverBadAnswer, SolverUnavailable
from agent_core.decisions.ladder import (
    LEVEL_SOLVER,
    REASON_UNAVAILABLE,
    Step,
    choose,
)

# Формулировка вопроса — одна на живой путь и на замер (см. докстроку модуля).
QUESTION = ("Сообщение клиента — это ТОЛЬКО условие выбора объекта (комнатность, цена, этаж, метраж, "
            "слова «парк», «ремонт»), без вопроса и без выбора?")
OPTIONS = {
    "да": "клиент называет только условия и ничего не спрашивает и не выбирает",
    "нет": "есть вопрос, просьба рассказать, выбор объекта, имя или телефон, либо это приветствие",
}

# Ответ, при котором локальный разбор можно применять. Константа, а не литерал по месту: значение
# сверяется и решением, и замером, и тестами.
PURE_ANSWER = "да"

# Функция «спросить решателя» — то, чем гейт пользуется. В проде это `make_ask(...)` из
# `decisions/client.py`, в тестах — двойник; поэтому модуль проверяется без сети.
AskSolver = Callable[[str, str, dict[str, str]], Awaitable[Decision]]


async def judge(text: str, *, ask: AskSolver, threshold: float) -> tuple[Step, Decision | None]:
    """Спросить гейт и вернуть ДВА взгляда: шаг лестницы и сам ответ решателя.

    Оба нужны. Живому пути нужен шаг (закрыт ли случай ЛОКАЛЬНО, то есть можно ли не звать агента),
    а замеру — ещё и ответ с уверенностью: без них нельзя отличить «гейт не пустил» от «решатель
    недоступен», и цена решения оказалась бы неизвестной.

    Никогда не бросает: сбой решателя — это закрытый гейт (идём к агенту, как сегодня).
    """
    try:
        decision = await ask(text, QUESTION, OPTIONS)
    except (SolverUnavailable, SolverBadAnswer):
        # Ловим ТОЛЬКО названные сбои сервиса: клиент уже упаковал в них сеть, таймаут и битый ответ.
        # Ловить `Exception` нельзя — это спрячет программные ошибки под видом «решатель недоступен».
        return choose(None, threshold=threshold, problem=REASON_UNAVAILABLE), None
    return choose(decision, threshold=threshold), decision


async def ask_gate(text: str, *, ask: AskSolver, threshold: float) -> Step:
    """Шаг лестницы — то, чем пользуются живой путь и замер (см. `judge` про второй взгляд)."""
    step, _decision = await judge(text, ask=ask, threshold=threshold)
    return step


def only_constraint(step: Step) -> bool:
    """Гейт уверенно говорит «только условие» — можно применять локальный разбор.

    Неуверенный ответ не открывает полосу: сегодня такой ход уходит к агенту, и менять это на
    догадке нельзя — клиент увидел бы фильтр, которого не просил.
    """
    return step.level == LEVEL_SOLVER and step.answer == PURE_ANSWER


def gate(*, ask: AskSolver, threshold: float) -> Callable[[str], Awaitable[bool]]:
    """Готовый гейт для диалога: спросить и сразу ответить «только условие?».

    Диалог получает ОДНУ функцию и не знает ни про решатель, ни про порог: так шов проверяется
    двойником без сети, а ставки остаются в одном месте.
    """
    async def check(text: str) -> bool:
        return only_constraint(await ask_gate(text, ask=ask, threshold=threshold))

    return check


def format_for_log(step: Step) -> str:
    """Исход гейта словами для журнала: видно, на каком уровне он закрыт и с какой уверенностью."""
    head = f"Уровень лестницы: {step.level}. "
    if step.closed_locally:
        return (f"{head}Решатель ответил «{step.answer}» с уверенностью {step.confidence:.2f} "
                f"(порог соблюдён).")
    return (f"{head}Решатель не закрыл вопрос ({step.reason}, уверенность {step.confidence:.2f}) — "
            f"решение за агентом.")
