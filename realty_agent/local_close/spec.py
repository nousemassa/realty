"""Локальный разбор условия для закрытия хода без агента.

**Зачем отдельный модуль, а не правка `booking/filter.py`.** Разбор продукта (`parse_constraints`)
используется в двух местах: в живом фолбэке (когда агент не вернул блок `FILTER`, мост фильтрует
каталог сам) и здесь, где решается, можно ли вообще НЕ звать агента. Расширение разбора меняло бы
первое — то есть поведение при выключенном флаге. Поэтому расширение живёт здесь и работает ТОЛЬКО на
пути локального закрытия: с выключенным флагом поведение не меняется ни в одном ходе, а расширение
проверяется замером.

**Что именно добавляется к разбору продукта** (видно по хранимой истории, 81 ход):

* комнатность в форме, которой пишут клиенты: «трёшки», «двушки» (разбор продукта знает «трёшку»,
  «двушку» — падеж, а клиенты пишут множественное число);
* цена сырым числом без «млн»: «дешевле 13000000» (разбор продукта ждёт «до/не дороже» и единицу).

Замер на 81 ходе: союз этого разбора с разбором продукта совпадает с выдачей агента на **11 из 12**
ходов, где агент применял фильтр; расходится на одном; сужает выдачу там, где агент не фильтровал,
на двух ходах.
"""
from __future__ import annotations

import re

from realty_agent.booking.filter import parse_constraints

# Слова комнатности, которых нет в разборе продукта (множественное число и разговорные формы).
ROOM_WORDS = (
    (r"студи", 1),
    (r"однушк|однокомн|1-комн", 1),
    (r"двушк|двухкомн|2-комн|евродв", 2),
    (r"трёшк|трешк|трехкомн|трёхкомн|3-комн", 3),
)
# Цена: «дешевле/до/не дороже/бюджет» плюс число — с единицей и без неё. Границы слова обязательны:
#: без них «Удобно 2026-10-01T10:00» читается как «до 2026» — граница слова обязательна.
PRICE_RE = re.compile(
    r"\b(?:дешевле|до|не дороже|бюджет|не больше)\b\D{0,12}(\d[\d\s]*)(?:[,.](\d+))?\s*(млн|тыс)?",
    re.IGNORECASE,
)


def extended_spec(text: str) -> dict | None:
    """Комнатность и цена в форме, которой пишут клиенты. `None` — если ничего не нашлось."""
    low = (text or "").lower().replace("\u00a0", " ")
    rooms = next((value for pattern, value in ROOM_WORDS if re.search(pattern, low)), None)
    price = None
    found = PRICE_RE.search(low)
    if found:
        whole = re.sub(r"\D", "", found.group(1))
        fraction = found.group(2) or ""
        value = float(f"{whole}.{fraction}") if fraction else float(whole or 0)
        price = int(value * {"млн": 1_000_000, "тыс": 1_000}.get((found.group(3) or "").lower(), 1))
    if rooms is None and price is None:
        return None
    return {"rooms": rooms, "price_max": price}


def local_spec(text: str) -> dict | None:
    """Спек для локального закрытия: разбор продукта плюс расширение, поля продукта приоритетны.

    Пусто — значит закрывать нечем: ход уходит агенту, как и раньше. Поле продукта не
    перекрывается расширением: продукт знает больше форм (этажи, слова, отрицания), и его разбор —
    то, чем уже пользуется фолбэк.
    """
    product = parse_constraints(text) or {}
    extra = extended_spec(text) or {}
    merged = dict(product)
    for key, value in extra.items():
        if value is not None and merged.get(key) is None:
            merged[key] = value
    return {key: value for key, value in merged.items() if value is not None} or None
