def parse_command(text: str) -> str | None:
    """'/Start@MyBot привет' → 'start'; обычный текст → None."""
    head = text.strip().split(maxsplit=1)[0] if text.strip() else ""
    if not head.startswith("/") or len(head) < 2:
        return None
    return head[1:].split("@", 1)[0].lower()


def is_consent_command(text: str) -> bool:
    return text.strip().lower() in {"/start", "согласен", "согласен(а)", "согласна"}
